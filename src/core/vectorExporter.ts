import { HalftoneDot, HalftoneSettings } from './types';

/**
 * Generates clean, standard SVG vector output
 */
export function generateSvg(
  dots: HalftoneDot[],
  width: number,
  height: number,
  settings: HalftoneSettings
): string {
  const {
    createBackground,
    backgroundColor,
    dotColor,
    layerName,
  } = settings;

  const bgElement = createBackground
    ? `  <rect id="Background" width="${width}" height="${height}" fill="${backgroundColor}" />\n`
    : '';

  const circles = dots
    .map(
      d =>
        `    <circle cx="${d.x}" cy="${d.y}" r="${d.radius}" fill="${dotColor || '#000000'}" />`
    )
    .join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">
  <title>${layerName || 'Halftone Maker Studio Artwork'}</title>
  <desc>Generated by Halftone Maker Studio</desc>
  <g id="${layerName || 'Halftone_Artwork'}">
${bgElement}    <g id="Dot_Group">
${circles}
    </g>
  </g>
</svg>`;
}

/**
 * Generates production-ready Adobe Illustrator ExtendScript (JSX) code
 * Optimized for Illustrator DOM speed:
 * - Suspends screen redraws
 * - Uses document.pathItems.ellipse(top, left, width, height)
 * - Single undo transaction
 * - Creates clean layer hierarchy: Layer -> Dot Group -> Ellipses
 */
export function generateExtendScript(
  dots: HalftoneDot[],
  width: number,
  height: number,
  settings: HalftoneSettings,
  documentTitle: string = 'Halftone Maker Studio'
): string {
  const {
    layerName,
    groupDots,
    createBackground,
    backgroundColor,
    dotColor,
    createNewDocument,
    putArtworkInNewLayer,
    fitArtboardToArtwork,
  } = settings;

  // Chunk dots into JSON data chunks to prevent string literal overflow in ExtendScript
  const dotsJson = JSON.stringify(
    dots.map(d => [
      Math.round(d.x * 10) / 10,
      Math.round(d.y * 10) / 10,
      Math.round(d.radius * 10) / 10,
    ])
  );

  return `/**
 * Halftone Maker Studio - Generated ExtendScript for Adobe Illustrator
 * Auto-generated: ${new Date().toISOString()}
 * Dots count: ${dots.length}
 */

(function () {
  try {
    if (!app.documents.length && ${!createNewDocument}) {
      alert("No active document found. Creating a new document.");
    }

    var doc;
    if (${createNewDocument} || !app.documents.length) {
      doc = app.documents.add(DocumentColorSpace.RGB, ${width}, ${height});
    } else {
      doc = app.activeDocument;
      ${
        fitArtboardToArtwork
          ? `var artboard = doc.artboards[doc.artboards.getActiveArtboardIndex()];
      artboard.artboardRect = [0, ${height}, ${width}, 0];`
          : ''
      }
    }

    // Temporarily disable redraw for high performance
    var originalRedraw = app.redraw;
    app.redraw = false;

    // Layer management
    var targetLayer;
    if (${putArtworkInNewLayer}) {
      targetLayer = doc.layers.add();
      targetLayer.name = "${layerName || 'Halftone Artwork'}";
    } else {
      targetLayer = doc.activeLayer;
    }

    // Helper: Parse Hex Color
    function hexToRgb(hex) {
      var c = hex.replace("#", "");
      if (c.length === 3) c = c[0]+c[0]+c[1]+c[1]+c[2]+c[2];
      var rgb = new RGBColor();
      rgb.red = parseInt(c.substring(0, 2), 16);
      rgb.green = parseInt(c.substring(2, 4), 16);
      rgb.blue = parseInt(c.substring(4, 6), 16);
      return rgb;
    }

    // Optional Background
    if (${createBackground}) {
      var bgRect = targetLayer.pathItems.rectangle(${height}, 0, ${width}, ${height});
      bgRect.name = "Background";
      bgRect.filled = true;
      bgRect.fillColor = hexToRgb("${backgroundColor || '#FFFFFF'}");
      bgRect.stroked = false;
    }

    // Parent group for dots
    var container = targetLayer;
    if (${groupDots}) {
      container = targetLayer.groupItems.add();
      container.name = "Dot Group";
    }

    var dotFill = hexToRgb("${dotColor || '#000000'}");

    // Dot Data: [x, y, radius]
    var dotData = ${dotsJson};
    var total = dotData.length;

    // Batch create vector ellipses in Illustrator coordinate space
    // Note: Illustrator origin is bottom-left, Y increases upwards.
    // SVG/Canvas origin is top-left, Y increases downwards.
    // top = height - (y - radius), left = x - radius, width = 2*radius, height = 2*radius
    for (var i = 0; i < total; i++) {
      var item = dotData[i];
      var cx = item[0];
      var cy = item[1];
      var r = item[2];
      var d = r * 2;

      // Illustrator ellipse params: top, left, width, height
      var top = ${height} - (cy - r);
      var left = cx - r;

      var circle = container.pathItems.ellipse(top, left, d, d);
      circle.filled = true;
      circle.fillColor = dotFill;
      circle.stroked = false;
    }

    // Restore redraw
    app.redraw = true;
    app.redraw();

    // Select the resulting artwork group
    if (${groupDots}) {
      doc.selection = [container];
    }

  } catch (err) {
    app.redraw = true;
    alert("Halftone Maker Studio Error: " + err.message);
  }
})();
`;
}

/**
 * Helper to translate SVG path 'd' commands into PostScript vector operators
 */
function svgPathToPostScript(d: string, height: number, shiftX = 0, shiftY = 0): string {
  if (!d) return '';
  let ps = 'newpath\n';
  const tokens = d.trim().split(/\s+/);
  let i = 0;
  while (i < tokens.length) {
    const cmd = tokens[i];
    if (cmd === 'M' && i + 2 < tokens.length) {
      const x = parseFloat(tokens[i + 1]) + shiftX;
      const y = height - (parseFloat(tokens[i + 2]) + shiftY);
      ps += `${x.toFixed(1)} ${y.toFixed(1)} moveto\n`;
      i += 3;
    } else if (cmd === 'L' && i + 2 < tokens.length) {
      const x = parseFloat(tokens[i + 1]) + shiftX;
      const y = height - (parseFloat(tokens[i + 2]) + shiftY);
      ps += `${x.toFixed(1)} ${y.toFixed(1)} lineto\n`;
      i += 3;
    } else if (cmd === 'Z') {
      ps += 'closepath\n';
      i += 1;
    } else {
      i++;
    }
  }
  return ps;
}

/**
 * Generates pure vector EPS (Encapsulated PostScript 3.0) output
 * Compatible with Adobe Illustrator, CorelDraw, and microstock vector submission.
 * Includes Layer 1 (Sticker Underlay), Layer 2 (Accent Stroke), and Layer 3 (Halftone Artwork).
 */
export function generateEpsFromElements(
  elements: Array<{ type: 'circle' | 'rect'; x: number; y: number; r?: number; w?: number; h?: number; rotation?: number }>,
  width: number,
  height: number,
  options: {
    transparentBg?: boolean;
    backgroundColor?: string;
    dotColor?: string;
    outlineOnly?: boolean;
    title?: string;
    stickerUnderlayPath?: string;
    stickerColor?: string;
    stickerShiftX?: number;
    stickerShiftY?: number;
    accentStrokePath?: string;
    accentStrokeColor?: string;
    accentStrokeWidth?: number;
    accentStrokeShiftX?: number;
    accentStrokeShiftY?: number;
  } = {}
): string {
  const {
    transparentBg = false,
    backgroundColor = '#FFFFFF',
    dotColor = '#000000',
    outlineOnly = false,
    title = 'Halftone Maker Studio Vector Artwork',
    stickerUnderlayPath,
    stickerColor = '#FFFFFF',
    stickerShiftX = 0,
    stickerShiftY = 0,
    accentStrokePath,
    accentStrokeColor = '#EF4444',
    accentStrokeWidth = 4,
    accentStrokeShiftX = 0,
    accentStrokeShiftY = 0,
  } = options;

  function hexToRgb(hex: string) {
    const c = (hex || '#000000').replace('#', '');
    const clean = c.length === 3 ? c[0] + c[0] + c[1] + c[1] + c[2] + c[2] : c;
    const r = ((parseInt(clean.substring(0, 2), 16) || 0) / 255).toFixed(3);
    const g = ((parseInt(clean.substring(2, 4), 16) || 0) / 255).toFixed(3);
    const b = ((parseInt(clean.substring(4, 6), 16) || 0) / 255).toFixed(3);
    return `${r} ${g} ${b}`;
  }

  const dotRgb = hexToRgb(dotColor);
  const bgRgb = hexToRgb(backgroundColor);

  let bgPs = '';
  if (!transparentBg) {
    bgPs = `% Background\n${bgRgb} setrgbcolor\n0 0 ${width} ${height} rectfill\n\n`;
  }

  let stickerPs = '';
  if (stickerUnderlayPath) {
    const stickerRgb = hexToRgb(stickerColor);
    stickerPs = `% LAYER 1 (Bottom): Independent Backing Shape (100% Pure Vector - No Raster)\ngsave\n${stickerRgb} setrgbcolor\n${svgPathToPostScript(stickerUnderlayPath, height, stickerShiftX, stickerShiftY)}fill\ngrestore\n\n`;
  }

  let strokePs = '';
  if (accentStrokePath && accentStrokeWidth > 0) {
    const strokeRgb = hexToRgb(accentStrokeColor);
    const totalShiftX = stickerShiftX + accentStrokeShiftX;
    const totalShiftY = stickerShiftY + accentStrokeShiftY;
    strokePs = `% LAYER 2 (Middle): Accent Contour Stroke (100% Pure Vector)\ngsave\n${strokeRgb} setrgbcolor\n${accentStrokeWidth} setlinewidth\n1 setlinejoin\n1 setlinecap\n${svgPathToPostScript(accentStrokePath, height, totalShiftX, totalShiftY)}stroke\ngrestore\n\n`;
  }

  let itemsPs = `% LAYER 3 (Top): Halftone Vector Dots\n${dotRgb} setrgbcolor\n`;
  if (outlineOnly) {
    itemsPs += `1 setlinewidth\n`;
  }

  for (let i = 0; i < elements.length; i++) {
    const el = elements[i];
    if (el.type === 'circle' && el.r) {
      // In PostScript, origin (0,0) is bottom-left
      const yPs = height - el.y;
      if (outlineOnly) {
        itemsPs += `newpath ${el.x.toFixed(1)} ${yPs.toFixed(1)} ${el.r.toFixed(1)} 0 360 arc stroke\n`;
      } else {
        itemsPs += `newpath ${el.x.toFixed(1)} ${yPs.toFixed(1)} ${el.r.toFixed(1)} 0 360 arc fill\n`;
      }
    } else if (el.type === 'rect' && el.w && el.h) {
      const yPs = height - (el.y + el.h);
      if (el.rotation) {
        itemsPs += `gsave\n${(el.x + el.w / 2).toFixed(1)} ${(height - (el.y + el.h / 2)).toFixed(1)} translate\n${(-el.rotation).toFixed(1)} rotate\n`;
        if (outlineOnly) {
          itemsPs += `${(-el.w / 2).toFixed(1)} ${(-el.h / 2).toFixed(1)} ${el.w.toFixed(1)} ${el.h.toFixed(1)} rectstroke\n`;
        } else {
          itemsPs += `${(-el.w / 2).toFixed(1)} ${(-el.h / 2).toFixed(1)} ${el.w.toFixed(1)} ${el.h.toFixed(1)} rectfill\n`;
        }
        itemsPs += `grestore\n`;
      } else {
        if (outlineOnly) {
          itemsPs += `${el.x.toFixed(1)} ${yPs.toFixed(1)} ${el.w.toFixed(1)} ${el.h.toFixed(1)} rectstroke\n`;
        } else {
          itemsPs += `${el.x.toFixed(1)} ${yPs.toFixed(1)} ${el.w.toFixed(1)} ${el.h.toFixed(1)} rectfill\n`;
        }
      }
    }
  }

  return `%!PS-Adobe-3.0 EPSF-3.0
%%Creator: Halftone Maker Studio
%%Title: ${title}
%%BoundingBox: 0 0 ${width} ${height}
%%HiResBoundingBox: 0 0 ${width} ${height}
%%Pages: 1
%%LanguageLevel: 2
%%EndComments
%%BeginProlog
%%EndProlog
%%Page: 1 1
${bgPs}${stickerPs}${strokePs}${itemsPs}
%%EOF
`;
}

